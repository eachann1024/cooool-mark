package update

import (
	"slices"
	"strings"
)

// LocalizedNotes holds user-facing release notes in one language.
type LocalizedNotes struct {
	Highlights   string   `json:"highlights,omitempty"`
	New          []string `json:"new,omitempty"`
	Improvements []string `json:"improvements,omitempty"`
	Fixes        []string `json:"fixes,omitempty"`
	Other        []string `json:"other,omitempty"`
}

// IsEmpty reports whether every section is empty.
func (n LocalizedNotes) IsEmpty() bool {
	return strings.TrimSpace(n.Highlights) == "" &&
		len(n.New) == 0 && len(n.Improvements) == 0 && len(n.Fixes) == 0 && len(n.Other) == 0
}

// Lines flattens the notes into display order: highlights, new, improvements, fixes, other.
func (n LocalizedNotes) Lines() []string {
	var out []string
	if h := strings.TrimSpace(n.Highlights); h != "" {
		out = append(out, h)
	}
	for _, list := range [][]string{n.New, n.Improvements, n.Fixes, n.Other} {
		for _, item := range list {
			if s := strings.TrimSpace(item); s != "" {
				out = append(out, s)
			}
		}
	}
	return out
}

// ReleaseAsset is one downloadable installer attached to a release.
type ReleaseAsset struct {
	Name        string `json:"name"`
	DownloadURL string `json:"browser_download_url"`
	Size        int64  `json:"size,omitempty"`
	SHA256      string `json:"sha256,omitempty"`
	Digest      string `json:"digest,omitempty"`
}

// EffectiveSHA256 returns the lowercase 64-character hex SHA-256 digest, or "" when absent or malformed.
func (a ReleaseAsset) EffectiveSHA256() string {
	raw := strings.TrimSpace(a.SHA256)
	if raw == "" {
		raw = strings.TrimPrefix(strings.TrimSpace(a.Digest), "sha256:")
	}
	raw = strings.ToLower(strings.TrimSpace(raw))
	if len(raw) != 64 {
		return ""
	}
	for i := 0; i < len(raw); i++ {
		c := raw[i]
		if !((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f')) {
			return ""
		}
	}
	return raw
}

// ReleaseEntry is one published version in updates/feed.json or GitHub Releases.
type ReleaseEntry struct {
	Version     string         `json:"version"`
	Tag         string         `json:"tag"`
	PublishedAt string         `json:"published_at,omitempty"`
	HTMLURL     string         `json:"html_url,omitempty"`
	Zh          LocalizedNotes `json:"zh"`
	En          LocalizedNotes `json:"en"`
	Assets      []ReleaseAsset `json:"assets,omitempty"`
}

// FeedDocument matches updates/feed.json generated by scripts/release/update-feed.mjs.
type FeedDocument struct {
	SchemaVersion int            `json:"schema_version"`
	Repo          string         `json:"repo"`
	UpdatedAt     string         `json:"updated_at"`
	LatestVersion string         `json:"latest_version"`
	LatestTag     string         `json:"latest_tag"`
	Releases      []ReleaseEntry `json:"releases"`
}

// AggregatedNotes is the cross-version changelog between the running version and the latest release.
type AggregatedNotes struct {
	FromVersion  string         `json:"from_version"`
	ToVersion    string         `json:"to_version"`
	VersionCount int            `json:"version_count"`
	HasNewer     bool           `json:"has_newer"`
	PublishedAt  string         `json:"published_at,omitempty"`
	MergedZh     LocalizedNotes `json:"merged_zh"`
	MergedEn     LocalizedNotes `json:"merged_en"`
	Versions     []ReleaseEntry `json:"versions"`
}

// ForLanguage returns the merged notes for the UI language, falling back to the other language.
func (a AggregatedNotes) ForLanguage(chinese bool) LocalizedNotes {
	if chinese {
		if !a.MergedZh.IsEmpty() {
			return a.MergedZh
		}
		return a.MergedEn
	}
	if !a.MergedEn.IsEmpty() {
		return a.MergedEn
	}
	return a.MergedZh
}

func looksChinese(text string) bool {
	if strings.Contains(text, "## 中文") || strings.Contains(text, "本次更新重点") ||
		strings.Contains(text, "### 新功能") || strings.Contains(text, "### 改进") ||
		strings.Contains(text, "### 修复") || strings.Contains(text, "✨ 新功能") {
		return true
	}
	for _, r := range text {
		if r >= 0x4E00 && r <= 0x9FFF {
			return true
		}
	}
	return false
}

// ParseReleaseBody splits a bilingual GitHub Release Markdown body into Zh and En sections.
func ParseReleaseBody(raw string) (zh LocalizedNotes, en LocalizedNotes) {
	norm := strings.TrimSpace(strings.ReplaceAll(raw, "\r\n", "\n"))
	if norm == "" {
		return LocalizedNotes{}, LocalizedNotes{}
	}

	var left, right string
	if idx := strings.Index(norm, "\n---\n"); idx >= 0 {
		left = strings.TrimSpace(norm[:idx])
		right = strings.TrimSpace(norm[idx+5:])
	} else if idx := strings.Index(norm, "\n---"); idx >= 0 {
		left = strings.TrimSpace(norm[:idx])
		right = strings.TrimSpace(norm[idx+4:])
	} else {
		parsed := parseSingleHalf(norm)
		return parsed, parsed
	}
	if right == "" {
		parsed := parseSingleHalf(left)
		return parsed, parsed
	}
	if looksChinese(right) && !looksChinese(left) {
		return parseSingleHalf(right), parseSingleHalf(left)
	}
	if looksChinese(left) && !looksChinese(right) {
		return parseSingleHalf(left), parseSingleHalf(right)
	}
	return parseSingleHalf(right), parseSingleHalf(left)
}

func parseSingleHalf(text string) LocalizedNotes {
	var out LocalizedNotes
	section := ""
	for _, rawLine := range strings.Split(text, "\n") {
		line := strings.TrimSpace(rawLine)
		if line == "" {
			continue
		}
		if strings.HasPrefix(line, "Website:") || strings.HasPrefix(line, "官网：") || strings.HasPrefix(line, "官网:") {
			section = "skip"
			continue
		}
		if (strings.HasPrefix(line, "🌈") || strings.Contains(line, "本次更新重点") || strings.Contains(line, "Highlights")) && out.Highlights == "" {
			highlight := strings.TrimLeft(line, "🌈# ")
			for _, prefix := range []string{"本次更新重点：", "本次更新重点:", "Highlights:", "Highlights："} {
				highlight = strings.TrimPrefix(highlight, prefix)
			}
			out.Highlights = strings.TrimSpace(highlight)
			continue
		}
		if strings.HasPrefix(line, "#") || strings.HasPrefix(line, "✨") || strings.HasPrefix(line, "🪐") || strings.HasPrefix(line, "🐛") {
			heading := strings.TrimSpace(strings.TrimLeft(line, "#✨🪐🐛 "))
			lower := strings.ToLower(heading)
			switch {
			case lower == "english" || heading == "中文":
				continue
			case lower == "download" || lower == "install" || strings.Contains(heading, "下载") || strings.Contains(heading, "安装"):
				section = "skip"
			case lower == "new" || strings.Contains(heading, "新功能") || strings.HasPrefix(lower, "new "):
				section = "new"
			case lower == "improvements" || lower == "improved" || strings.Contains(heading, "改进") || strings.Contains(heading, "优化"):
				section = "improvements"
			case lower == "fixes" || lower == "fixed" || strings.Contains(heading, "修复"):
				section = "fixes"
			case lower == "other" || strings.Contains(heading, "其他"):
				section = "other"
			default:
				switch {
				case strings.HasPrefix(line, "✨"):
					section = "new"
				case strings.HasPrefix(line, "🪐"):
					section = "improvements"
				case strings.HasPrefix(line, "🐛"):
					section = "fixes"
				}
			}
			continue
		}
		if section == "skip" {
			continue
		}
		var bullet string
		switch {
		case strings.HasPrefix(line, "- "), strings.HasPrefix(line, "* "):
			bullet = strings.TrimSpace(line[2:])
		case strings.HasPrefix(line, "• "):
			bullet = strings.TrimSpace(strings.TrimPrefix(line, "•"))
		}
		if bullet == "" {
			continue
		}
		bullet = strings.ReplaceAll(bullet, "**", "")
		switch section {
		case "new":
			out.New = appendUnique(out.New, bullet)
		case "fixes":
			out.Fixes = appendUnique(out.Fixes, bullet)
		case "other":
			out.Other = appendUnique(out.Other, bullet)
		default:
			out.Improvements = appendUnique(out.Improvements, bullet)
		}
	}
	return out
}

func appendUnique(dst []string, item string) []string {
	if item == "" || slices.Contains(dst, item) {
		return dst
	}
	return append(dst, item)
}

func mergeLocalized(dst *LocalizedNotes, src LocalizedNotes) {
	if dst.Highlights == "" {
		dst.Highlights = src.Highlights
	}
	for _, item := range src.New {
		dst.New = appendUnique(dst.New, item)
	}
	for _, item := range src.Improvements {
		dst.Improvements = appendUnique(dst.Improvements, item)
	}
	for _, item := range src.Fixes {
		dst.Fixes = appendUnique(dst.Fixes, item)
	}
	for _, item := range src.Other {
		dst.Other = appendUnique(dst.Other, item)
	}
}

func normalizeEntry(r ReleaseEntry) (ReleaseEntry, bool) {
	ver, tag, _, ok := ParseReleaseTag(r.Tag)
	if !ok {
		ver, tag, _, ok = ParseReleaseTag(r.Version)
		if !ok {
			return r, false
		}
		if !strings.HasPrefix(strings.ToLower(tag), "v") {
			tag = "v" + ver
		}
	} else if strings.TrimSpace(r.Version) != "" {
		if other, _, _, ok2 := ParseReleaseTag(r.Version); ok2 && other != ver {
			return r, false
		}
	}
	r.Version = ver
	r.Tag = tag
	return r, true
}

// AggregateReleases merges the notes of every release newer than currentVersion.
func AggregateReleases(releases []ReleaseEntry, currentVersion string) AggregatedNotes {
	var newer []ReleaseEntry
	for _, r := range releases {
		if entry, ok := normalizeEntry(r); ok && CompareVersion(entry.Version, currentVersion) > 0 {
			newer = append(newer, entry)
		}
	}
	if len(newer) == 0 {
		return AggregatedNotes{FromVersion: currentVersion, ToVersion: currentVersion}
	}
	slices.SortFunc(newer, func(a, b ReleaseEntry) int { return CompareVersion(b.Version, a.Version) })
	out := AggregatedNotes{
		FromVersion:  currentVersion,
		ToVersion:    newer[0].Version,
		VersionCount: len(newer),
		HasNewer:     true,
		PublishedAt:  newer[0].PublishedAt,
		Versions:     newer,
	}
	for _, r := range newer {
		mergeLocalized(&out.MergedZh, r.Zh)
		mergeLocalized(&out.MergedEn, r.En)
	}
	return out
}
